"""Regenerate the classic browser bundle after editing JS sources (optional)."""
from pathlib import Path
import re
root = Path(__file__).resolve().parent
model = re.sub(r'^export ', '', (root / 'model.js').read_text(), flags=re.M)
app = re.sub(r'^import .*?;\n', '', (root / 'app.js').read_text(), count=1)
(root / 'offline-bundle.js').write_text('/* Generated by bundle.py. Opens directly via file://, including Firefox. */\n(() => {\n' + model + '\n' + (root / 'offline.js').read_text() + '\n' + app + '\n})();\n')
